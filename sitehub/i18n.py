def t(text: str, lang: str, **kw) -> str:
    if lang == "en":
        s = EN_KEYS.get(text) or EN.get(text, text)
    else:
        s = RU_KEYS.get(text, text)
    if kw:
        try:
            return s.format(**kw)
        except (KeyError, IndexError, ValueError):
            return s
    return s


def ago(ts: int | None, lang: str) -> str:
    if not ts:
        return "—"
    d = int(time.time()) - int(ts)
    if lang == "en":
        if d < 60:
            return "just now"
        if d < 3600:
            return f"{d // 60} min ago"
        if d < 86400:
            return f"{d // 3600} h ago"
        return f"{d // 86400} d ago"
    if d < 60:
        return "только что"
    if d < 3600:
        return f"{d // 60} мин назад"
    if d < 86400:
        return f"{d // 3600} ч назад"
    return f"{d // 86400} дн назад"
